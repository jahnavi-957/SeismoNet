def _write_csv(path, header, rows):
    with open(path, "w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=header)
        writer.writeheader()
        for row in rows:
            writer.writerow(row)
    return path


def test_verify_noise_metadata_accepts_pure_noise_schema(tmp_path):
    path = tmp_path / "noise.csv"
    header = ["source_id", "trace_dt_s", "trace_npts", "trace_name"]
    rows = [
        {"source_id": "20131205T210857", "trace_dt_s": "0.01", "trace_npts": "12000",
         "trace_name": "20131205T210857.IV.ORZI..HN"},
        {"source_id": "20070528T142806", "trace_dt_s": "0.01", "trace_npts": "12000",
         "trace_name": "20070528T142806.IV.BOB..HH"},
    ]
    report = verify_noise_metadata(_write_csv(path, header, rows))
    assert report.ok is True
    assert report.has_phase_pick_columns is False
    assert report.has_event_only_columns is False
    assert report.n_rows == 2
    assert report.npts_values == ["12000"]
    assert report.dt_values == ["0.01"]


def test_verify_noise_metadata_flags_reference_phase_columns(tmp_path):
    path = tmp_path / "noise_with_phases.csv"
    header = ["source_id", "trace_dt_s", "trace_npts", "trace_name", "trace_P_arrival_sample"]
    rows = [{"source_id": "x", "trace_dt_s": "0.01", "trace_npts": "12000", "trace_name": "a",
             "trace_P_arrival_sample": "100"}]
    report = verify_noise_metadata(_write_csv(path, header, rows))
    assert report.ok is False
    assert report.has_phase_pick_columns is True
    assert any("phase columns present" in reason for reason in report.reasons)


def test_verify_noise_metadata_flags_duplicates_and_mixed_lengths(tmp_path):
    path = tmp_path / "noise_bad.csv"
    header = ["source_id", "trace_dt_s", "trace_npts", "trace_name"]
    rows = [
        {"source_id": "a", "trace_dt_s": "0.01", "trace_npts": "12000", "trace_name": "same"},
        {"source_id": "b", "trace_dt_s": "0.01", "trace_npts": "6000", "trace_name": "same"},
    ]
    report = verify_noise_metadata(_write_csv(path, header, rows))
    assert report.ok is False
    assert any("duplicate" in reason for reason in report.reasons)
    assert any("multiple trace_npts" in reason for reason in report.reasons)
