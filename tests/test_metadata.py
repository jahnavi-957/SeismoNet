"""FR-010 (event-id construction) and FR-011 (stratification) — synthetic rows only.

Every fixture here is generated by the test, so no dataset value is fabricated and no unit test
depends on the INSTANCE files being present (NFR-010).
"""
import csv

import pytest

from seismonet.metadata import (
    DEFAULT_FALLBACK_KEYS,
    canonical_event_key,
    construct_event_id,
    event_id_coverage,
    event_id_source,
    quantile_edges,
    stratify_by,
    stratify_by_quantiles,
    verify_noise_metadata,
)


def _event_row(**overrides):
    """A synthetic event metadata row with both a direct id and fallback fields."""
    row = {
        "trace_name": "20000101T000000.XX.AAA..HH",
        "source_id": "12345",
        "source_origin_time": "2000-01-01T00:00:00.00Z",
        "source_latitude_deg": "40.0",
        "source_longitude_deg": "10.0",
    }
    row.update(overrides)
    return row


# --------------------------------------------------------------------------------------
# FR-010 — construct_event_id
# --------------------------------------------------------------------------------------


def test_prefers_source_id_and_never_replaces_it():
    # Fallback fields are present but deliberately inconsistent with the real id; the direct
    # source_id must win and must not be overwritten by a constructed value.
    row = _event_row(source_latitude_deg="99.9")
    assert construct_event_id(row, DEFAULT_FALLBACK_KEYS) == "12345"
    assert event_id_source(row, DEFAULT_FALLBACK_KEYS) == "source_id"


def test_prefers_event_id_column_over_source_id():
    row = _event_row(event_id="evt-abc")
    assert construct_event_id(row, DEFAULT_FALLBACK_KEYS) == "evt-abc"
    assert event_id_source(row, DEFAULT_FALLBACK_KEYS) == "event_id"


def test_fallback_is_deterministic_for_the_same_event():
    # Two synthetic rows from the same event (origin time + location), with no direct id.
    a = _event_row(trace_name="t-a", source_id="", event_id="")
    b = _event_row(trace_name="t-b", source_id="", event_id="")
    id_a = construct_event_id(a, DEFAULT_FALLBACK_KEYS)
    id_b = construct_event_id(b, DEFAULT_FALLBACK_KEYS)
    assert id_a is not None
    assert id_a == id_b
    assert event_id_source(a, DEFAULT_FALLBACK_KEYS) == "constructed"


def test_fallback_distinguishes_different_events():
    a = _event_row(trace_name="t-a", source_id="", event_id="")
    b = _event_row(trace_name="t-b", source_id="", event_id="", source_latitude_deg="41.0")
    assert construct_event_id(a, DEFAULT_FALLBACK_KEYS) != construct_event_id(b, DEFAULT_FALLBACK_KEYS)


def test_fallback_normalises_equivalent_time_representations():
    a = _event_row(trace_name="t-a", source_id="", event_id="",
                   source_origin_time="2000-01-01T00:00:00.05Z")
    b = _event_row(trace_name="t-b", source_id="", event_id="",
                   source_origin_time="2000-01-01T00:00:00.050000+00:00")
    assert construct_event_id(a, DEFAULT_FALLBACK_KEYS) == construct_event_id(b, DEFAULT_FALLBACK_KEYS)


def test_fallback_normalises_coordinate_precision():
    a = _event_row(trace_name="t-a", source_id="", event_id="", source_latitude_deg="40.0")
    b = _event_row(trace_name="t-b", source_id="", event_id="", source_latitude_deg="40.00000")
    assert construct_event_id(a, DEFAULT_FALLBACK_KEYS) == construct_event_id(b, DEFAULT_FALLBACK_KEYS)


def test_fallback_returns_none_when_a_field_is_missing():
    row = _event_row(source_id="", event_id="", source_longitude_deg="")
    assert construct_event_id(row, DEFAULT_FALLBACK_KEYS) is None
    assert canonical_event_key(row, DEFAULT_FALLBACK_KEYS) is None


def test_fallback_strict_raises_when_incomplete():
    row = _event_row(source_id="", event_id="", source_longitude_deg="")
    with pytest.raises(ValueError):
        construct_event_id(row, DEFAULT_FALLBACK_KEYS, strict=True)


def test_canonical_key_is_readable_and_documented():
    row = _event_row(source_id="", event_id="")
    key = canonical_event_key(row, DEFAULT_FALLBACK_KEYS)
    assert key is not None
    # The rule is inspectable: each fallback field appears as key=value.
    for field_name in DEFAULT_FALLBACK_KEYS:
        assert f"{field_name}=" in key


def test_event_id_coverage_counts_direct_and_constructed():
    rows = [
        _event_row(trace_name="t1", source_id="7"),
        _event_row(trace_name="t2", source_id="", event_id=""),
        _event_row(trace_name="t3", source_id="", event_id="", source_longitude_deg=""),
    ]
    coverage = event_id_coverage(rows, DEFAULT_FALLBACK_KEYS)
    assert coverage.n_total == 3
    assert coverage.n_assigned == 2
    assert coverage.n_missing == 1
    assert coverage.by_source["source_id"] == 1
    assert coverage.by_source["constructed"] == 1
    assert coverage.missing_trace_names == ["t3"]
    assert coverage.summary()["coverage"] == pytest.approx(2 / 3)


