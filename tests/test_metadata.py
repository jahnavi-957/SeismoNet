# FR-011 — stratify_by
# --------------------------------------------------------------------------------------


def _metric_rows():
    return {
        "t1": {"trace_Z_snr_db": "5.0", "source_magnitude": "2.0"},
        "t2": {"trace_Z_snr_db": "15.0", "source_magnitude": "3.0"},
        "t3": {"trace_Z_snr_db": "25.0", "source_magnitude": "4.0"},
        "t4": {"trace_Z_snr_db": "", "source_magnitude": "5.0"},  # blank -> missing
    }


def test_stratify_by_groups_values_into_bins():
    result = stratify_by(_metric_rows(), "trace_Z_snr_db", [10.0, 20.0])
    assert result.available is True
    assert result.labels == ("[-,10)", "[10,20)", "[20,+)")
    assert result.groups["[-,10)"] == ["t1"]
    assert result.groups["[10,20)"] == ["t2"]
    assert result.groups["[20,+)"] == ["t3"]
    assert result.missing == ["t4"]
    assert result.counts() == {"[-,10)": 1, "[10,20)": 1, "[20,+)": 1}


def test_stratify_by_documents_absent_field():
    result = stratify_by(_metric_rows(), "path_hyp_distance_km", [10.0])
    assert result.available is False
    assert result.n_grouped == 0
    assert "not present" in result.detail
    assert len(result.missing) == 4


def test_stratify_by_rejects_non_increasing_bins():
    with pytest.raises(ValueError):
        stratify_by(_metric_rows(), "trace_Z_snr_db", [20.0, 10.0])


def test_stratify_by_custom_labels_length_checked():
    with pytest.raises(ValueError):
        stratify_by(_metric_rows(), "trace_Z_snr_db", [10.0, 20.0], labels=["only-one"])


def test_quantile_edges_covers_range_and_is_ordered():
    edges = quantile_edges([1, 2, 3, 4, 5, 6, 7, 8], 4)
    assert edges[0] == 1.0
    assert edges[-1] == 8.0
    assert list(edges) == sorted(edges)


def test_stratify_by_quantiles_groups_comparable_counts():
    rows = {f"t{i}": {"source_magnitude": str(float(i))} for i in range(20)}
    result = stratify_by_quantiles(rows, "source_magnitude", 4)
    counts = result.counts()
    assert sum(counts.values()) == 20
    assert all(count > 0 for count in counts.values())


def test_stratify_by_quantiles_documents_absent_field():
    rows = {"t1": {"trace_Z_snr_db": "1.0"}}
    result = stratify_by_quantiles(rows, "source_magnitude", 4)
    assert result.available is False
    assert "unavailable" in result.detail


