@pytest.fixture
def window_length() -> int:
    return 128  # small, divisible by 2**3 and 2**4 — keeps tests fast


@pytest.fixture
def synthetic_hdf5(tmp_path):
    """Build a small **synthetic** INSTANCE-like HDF5 (never a real waveform record).

    The layout mirrors what the loader and screener read in production — a ``data`` group of
    per-trace datasets plus a ``data_format`` group — so the guards can be exercised without the
    dataset. Everything written here is generated by the test, so no dataset value is ever
    fabricated or asserted as if it were real (PRD §1 "do not invent results").

    ``records`` maps ``trace_name`` -> array-like. Keyword arguments control only the declared
    format, so a test can deliberately declare the *wrong* order, rate or dtype.
    """
    h5py = pytest.importorskip("h5py")
    counter = itertools.count()

    def _make(
        records,
        *,
        component_order="ENZ",
        dimension_order="CW",
        sampling_rate=None,
        dt_s=None,
        dtype="int32",
    ):
        path = tmp_path / f"synthetic_{next(counter)}.hdf5"
        with h5py.File(str(path), "w") as handle:
            fmt = handle.create_group("data_format")
            if component_order is not None:
                fmt["component_order"] = np.bytes_(component_order)
            if dimension_order is not None:
                fmt["dimension_order"] = np.bytes_(dimension_order)
            if sampling_rate is not None:
                fmt["sampling_rate"] = np.float64(sampling_rate)
            if dt_s is not None:
                fmt["trace_dt_s"] = np.float64(dt_s)
            fmt["unit"] = np.bytes_("counts")
            data = handle.create_group("data")
            for name, array in records.items():
                data.create_dataset(name, data=np.asarray(array, dtype=dtype))
        return path

    return _make
